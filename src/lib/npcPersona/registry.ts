/** 根据在场 NPC 列表筛选相关的人格卡 */
export function selectActivePersonaCards(
  presentNpcIds: string[],
  mentionedNpcIds?: string[],
): NpcPersonaCard[] {
  const allIds = new Set([...presentNpcIds, ...(mentionedNpcIds ?? [])]);
  const cards: NpcPersonaCard[] = [];
  for (const id of allIds) {
    const card = NPC_PERSONA_CARDS[id];
    if (card) cards.push(card);
  }
  return cards.slice(0, 3); // 每回合最多展示 3 个 NPC
}

